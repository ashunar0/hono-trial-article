/**
 * Writes src/routes.gen.ts from the files:
 * - src/routes/**\/index.ts: each `export const GET | POST | PUT | PATCH | DELETE` becomes a route.
 *   The directory is the path; [id] is :id; files and directories starting with _ are skipped
 * - src/{routes,middleware}/**\/_queries.ts: each `export function xxxQueries` is wired to the db
 * - AppType: every route's input and output, for hc. One entry per route, side by side, not a chain
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const src = join(import.meta.dirname, "../src");
const out = join(src, "routes.gen.ts");
const methods = ["GET", "POST", "PUT", "PATCH", "DELETE"] as const;

const filesIn = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name.startsWith("_") ? [] : filesIn(path);
    return [path];
  });

const importPath = (file: string) => `./${relative(src, file).replace(/\.ts$/, "")}`;

// routes
type Route = { path: string; method: (typeof methods)[number]; name: string; file: string };

const routeFiles = filesIn(join(src, "routes")).filter((f) => f.endsWith("/index.ts"));
const routes: Route[] = routeFiles.flatMap((file, i) => {
  const dir = relative(join(src, "routes"), file).replace(/\/?index\.ts$/, "");
  const path = `/${dir}`.replace(/\[(\w+)\]/g, ":$1");
  const code = readFileSync(file, "utf8");
  return methods
    .filter((m) => new RegExp(`^export const ${m}\\b`, "m").test(code))
    .map((method) => ({ path, method, name: `route${i}`, file }));
});

/** Static segments before :params, so /articles/new would win over /articles/:id */
const rank = (path: string) => path.split("/").map((s) => (s.startsWith(":") ? "1" : `0${s}`));
const byPath = (a: Route, b: Route) => {
  const [x, y] = [rank(a.path), rank(b.path)];
  for (let i = 0; i < Math.min(x.length, y.length); i++) {
    if (x[i] !== y[i]) return x[i]! < y[i]! ? -1 : 1;
  }
  return x.length - y.length || methods.indexOf(a.method) - methods.indexOf(b.method);
};
routes.sort(byPath);

// queries
const queryFiles = ["routes", "middleware"]
  .flatMap((d) => filesIn(join(src, d)))
  .filter((f) => f.endsWith("/_queries.ts"))
  .sort();
const queries = queryFiles.flatMap((file) =>
  [...readFileSync(file, "utf8").matchAll(/^export function (\w+Queries)\b/gm)].map((m) => ({
    name: m[1]!,
    file,
  })),
);

const lines = [
  "// Generated by scripts/gen.ts from src/routes and src/middleware. Do not edit; run `pnpm gen`",
  'import type { Hono } from "hono";',
  'import type { Db } from "./db";',
  'import type { AppEnv } from "./factory";',
  'import type { Endpoint } from "./lib/route-types";',
  ...queries.map((q) => `import { ${q.name} } from "${importPath(q.file)}";`),
  ...routeFiles.map((file, i) => `import * as route${i} from "${importPath(file)}";`),
  "",
  "/** Every _queries.ts, wired to one db */",
  "export const makeQueries = (db: Db) => ({",
  ...queries.map((q) => `  ${q.name}: ${q.name}(db),`),
  "});",
  "",
  "/** Every route file and method, static paths first */",
  "export function registerRoutes(app: Hono<AppEnv>) {",
  ...routes.map((r) => `  app.${r.method.toLowerCase()}("${r.path}", ...${r.name}.${r.method});`),
  "}",
  "",
  "/** Every route's input and output. hc<AppType>(url) gives a typed client */",
  "export type AppType = Hono<",
  "  AppEnv,",
  ...routes.map(
    (r, i) =>
      `  ${i === 0 ? "" : "& "}Endpoint<"${r.method.toLowerCase()}", "${r.path}", typeof ${r.name}.${r.method}>`,
  ),
  ">;",
  "",
];

writeFileSync(out, lines.join("\n"));
console.log(`${relative(process.cwd(), out)}: ${routes.length} routes, ${queries.length} queries`);
