/**
 * Writes src/routes.gen.ts from the files:
 * - src/routes/**\/index.ts and page.tsx: each exported GET | POST | PUT | PATCH | DELETE becomes a route.
 *   The directory is the path; [id] is :id; files and directories starting with _ are skipped.
 *   page.tsx is the screen (HTML) at the path, index.ts the API (JSON) at /api + the path
 * - src/{routes,middleware}/**\/_queries.ts: each exported xxxQueries is wired to the db
 * - AppType: every API route's input and output, for hc. One entry per route, side by side, not a chain
 *
 * Exports are read with oxc-parser, the way Void reads them. A file it cannot make sense of stops
 * the generation with a message, rather than being left out in silence.
 * `--watch` regenerates on every change under src/routes and src/middleware, and keeps going on errors
 */
import { existsSync, readdirSync, readFileSync, watch, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseSync } from "oxc-parser";

const src = join(import.meta.dirname, "../src");
const out = join(src, "routes.gen.ts");
const watched = ["routes", "middleware"].map((d) => join(src, d));
const methods = ["GET", "POST", "PUT", "PATCH", "DELETE"] as const;
type Method = (typeof methods)[number];

const filesIn = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name.startsWith("_") ? [] : filesIn(path);
    return [path];
  });

const at = (file: string) => relative(process.cwd(), file);

const importPath = (file: string) => `./${relative(src, file).replace(/\.tsx?$/, "")}`;

/** The names a file exports as values. Type exports are left out */
const valueExportsOf = (file: string, problems: string[]) => {
  const parsed = parseSync(file, readFileSync(file, "utf8"));
  for (const error of parsed.errors) problems.push(`${at(file)}: ${error.message}`);

  return parsed.module.staticExports
    .flatMap((e) => e.entries)
    .filter((entry) => !entry.isType)
    .flatMap((entry) => (entry.exportName.name ? [entry.exportName.name] : []));
};

/** Static segments before :params, so /articles/new would win over /articles/:id */
const rank = (path: string) => path.split("/").map((s) => (s.startsWith(":") ? "1" : `0${s}`));
const byPath = (a: { path: string; method: Method }, b: { path: string; method: Method }) => {
  const [x, y] = [rank(a.path), rank(b.path)];
  for (let i = 0; i < Math.min(x.length, y.length); i++) {
    if (x[i] !== y[i]) return x[i]! < y[i]! ? -1 : 1;
  }
  return x.length - y.length || methods.indexOf(a.method) - methods.indexOf(b.method);
};

/** The generated source, or the problems that stop it */
function generate(): { code: string } | { problems: string[] } {
  const problems: string[] = [];

  // routes
  const routeFiles = filesIn(join(src, "routes")).filter((f) => /\/(index\.ts|page\.tsx)$/.test(f));
  const routes = routeFiles.flatMap((file, i) => {
    const api = file.endsWith("/index.ts");
    const dir = relative(join(src, "routes"), file).replace(/\/?(index\.ts|page\.tsx)$/, "");
    const path = `${api ? "/api" : ""}/${dir}`.replace(/\[(\w+)\]/g, ":$1").replace(/(.)\/$/, "$1");
    const names = valueExportsOf(file, problems);

    for (const name of names) {
      const meant = methods.find((m) => m === name.toUpperCase());
      if (meant && meant !== name) problems.push(`${at(file)}: export ${name} is not a method. Did you mean ${meant}?`);
    }
    const found = methods.filter((m) => names.includes(m));
    if (found.length === 0)
      problems.push(`${at(file)}: no ${methods.join(" / ")} export, so it is no route`);

    return found.map((method) => ({ path, method, name: `route${i}`, file, api }));
  });
  routes.sort(byPath);

  // queries
  const queryFiles = watched
    .flatMap((d) => filesIn(d))
    .filter((f) => f.endsWith("/_queries.ts"))
    .sort();
  const queries = queryFiles.flatMap((file) => {
    const names = valueExportsOf(file, problems).filter((n) => n.endsWith("Queries"));
    if (names.length === 0) problems.push(`${at(file)}: no xxxQueries export to wire to the db`);

    return names.map((name) => ({ name, file }));
  });
  for (const [i, q] of queries.entries()) {
    const first = queries.findIndex((other) => other.name === q.name);
    if (first !== i)
      problems.push(`${at(q.file)}: ${q.name} is also in ${at(queries[first]!.file)}. Names must differ`);
  }

  if (problems.length > 0) return { problems };

  const lines = [
    "// Generated by scripts/gen.ts from src/routes and src/middleware. Do not edit; run `pnpm gen`",
    'import type { Hono } from "hono";',
    'import type { Db } from "./db";',
    'import type { AppEnv } from "./factory";',
    'import type { Endpoint } from "./lib/route-types";',
    ...queries.map((q) => `import { ${q.name} } from "${importPath(q.file)}";`),
    ...routeFiles.map((file, i) => `import * as route${i} from "${importPath(file)}";`),
    "",
    "/** Every _queries.ts, wired to one db */",
    "export const makeQueries = (db: Db) => ({",
    ...queries.map((q) => `  ${q.name}: ${q.name}(db),`),
    "});",
    "",
    "/** Every route file and method, static paths first */",
    "export function registerRoutes(app: Hono<AppEnv>) {",
    ...routes.map((r) => `  app.${r.method.toLowerCase()}("${r.path}", ...${r.name}.${r.method});`),
    "}",
    "",
    "/** Every API route's input and output. hc<AppType>(url) gives a typed client */",
    "export type AppType = Hono<",
    "  AppEnv,",
    ...routes.filter((r) => r.api).map(
      (r, i) =>
        `  ${i === 0 ? "" : "& "}Endpoint<"${r.method.toLowerCase()}", "${r.path}", typeof ${r.name}.${r.method}>`,
    ),
    ">;",
    "",
  ];

  return { code: lines.join("\n") };
}

/** Writes only when the code changed, so saving a file does not touch routes.gen.ts for nothing */
function run(): boolean {
  const result = generate();
  if ("problems" in result) {
    console.error(`${at(out)} not written:\n${result.problems.map((p) => `  ${p}`).join("\n")}`);
    return false;
  }
  if (!existsSync(out) || readFileSync(out, "utf8") !== result.code) {
    writeFileSync(out, result.code);
    console.log(`${at(out)} written`);
  }
  return true;
}

if (process.argv.includes("--watch")) {
  run();
  let timer: NodeJS.Timeout | undefined;
  for (const dir of watched) {
    watch(dir, { recursive: true }, () => {
      clearTimeout(timer);
      timer = setTimeout(run, 50);
    });
  }
  console.log(`watching ${watched.map(at).join(", ")}`);
} else if (!run()) {
  process.exit(1);
}
